-- Pipeline stages for every pipeline, matching the real execution order.
INSERT INTO app.pipeline_stage (pipeline_id, stage_order, stage_name, stage_kind, description)
SELECT p.pipeline_id, s.ord, s.nm, s.kind, s.descr
FROM app.etl_pipeline p
CROSS JOIN (VALUES
  (1, 'Extract from source', 'extract',   'Read the source file or connection'),
  (2, 'Stage raw rows',      'stage',     'Land rows in staging with a batch identifier'),
  (3, 'Validate records',    'validate',  'Apply type, null, key and range rules'),
  (4, 'Transform to model',  'transform', 'Derive keys, resolve dimension surrogates'),
  (5, 'Load warehouse',      'load',      'Upsert dimensions and insert facts'),
  (6, 'Reconcile totals',    'reconcile', 'Compare source and warehouse totals')
) AS s(ord, nm, kind, descr)
WHERE p.engine = 'retailflow-native'
  AND NOT EXISTS (SELECT 1 FROM app.pipeline_stage ps WHERE ps.pipeline_id = p.pipeline_id);

