-- ---------------------------------------------------------------- dim_date
INSERT INTO warehouse.dim_date (
    date_key, full_date, year, quarter, month, month_name, day,
    day_of_week, day_name, iso_week, is_weekend
)
SELECT
    to_char(d, 'YYYYMMDD')::int, d::date, extract(year from d)::int,
    extract(quarter from d)::int, extract(month from d)::int,
    trim(to_char(d, 'Month')), extract(day from d)::int,
    extract(dow from d)::int, trim(to_char(d, 'Day')),
    extract(week from d)::int, extract(dow from d) IN (0, 6)
FROM generate_series('2016-01-01'::date, '2020-12-31'::date, '1 day') AS d
ON CONFLICT (date_key) DO NOTHING;

-- ----------------------------------------------------- Brazilian state regions
WITH region_map (state, region) AS (VALUES
  ('AC','North'),('AP','North'),('AM','North'),('PA','North'),('RO','North'),('RR','North'),('TO','North'),
  ('AL','Northeast'),('BA','Northeast'),('CE','Northeast'),('MA','Northeast'),('PB','Northeast'),
  ('PE','Northeast'),('PI','Northeast'),('RN','Northeast'),('SE','Northeast'),
  ('DF','Central-West'),('GO','Central-West'),('MT','Central-West'),('MS','Central-West'),
  ('ES','Southeast'),('MG','Southeast'),('RJ','Southeast'),('SP','Southeast'),
  ('PR','South'),('RS','South'),('SC','South')
)
INSERT INTO warehouse.dim_geography (city, state, region)
SELECT DISTINCT nullif(trim(customer_city), ''), rm.state, rm.region
FROM staging.stg_order_items s
JOIN region_map rm ON rm.state = upper(trim(s.customer_state))
WHERE nullif(trim(s.customer_city), '') IS NOT NULL
ON CONFLICT (city, state) DO NOTHING;

